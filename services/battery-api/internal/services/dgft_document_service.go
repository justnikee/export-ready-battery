// GenerateClaimPDF produces a formatted DGFT claim application PDF.
func GenerateClaimPDF(claim *models.DGFTClaim, scheme *models.DGFTSchemeConfig, tenantName string) (*bytes.Buffer, error) {
	pdf := gofpdf.New("P", "mm", "A4", "")
	pdf.SetAutoPageBreak(true, 20)
	pdf.AddPage()

	// --- HEADER ---
	pdf.SetFillColor(23, 37, 84)
	pdf.Rect(0, 0, 210, 35, "F")
	pdf.SetFont("Arial", "B", 20)
	pdf.SetTextColor(255, 255, 255)
	pdf.SetXY(15, 12)
	pdf.Cell(0, 10, "DGFT EXPORT INCENTIVE CLAIM")

	pdf.SetFont("Arial", "", 10)
	pdf.SetXY(15, 22)
	pdf.Cell(0, 6, fmt.Sprintf("Scheme: %s", scheme.Name))

	// --- CLAIM INFO BOX ---
	drawSectionBox(pdf, 15, 42, 180, 55)
	pdf.SetFont("Arial", "B", 11)
	pdf.SetTextColor(23, 37, 84)
	pdf.SetXY(20, 46)
	pdf.Cell(0, 6, "Claim Details")

	pdf.SetFont("Arial", "", 10)
	pdf.SetTextColor(33, 33, 33)
	leftX, rightX := 20.0, 110.0
	rowY := 55.0
	lineH := 6.0

	infoPairs := []struct{ label, value string }{
		{"Claim ID:", claim.ID},
		{"Period:", fmt.Sprintf("%s to %s", formatDateStr(claim.ClaimPeriodStart), formatDateStr(claim.ClaimPeriodEnd))},
		{"HSN Code:", claim.HSNCode},
		{"Destination:", claim.DestinationCountry},
		{"Exporter:", tenantName},
		{"Status:", claim.Status},
	}

	for i, pair := range infoPairs {
		x := leftX
		if i%2 == 1 {
			x = rightX
		}
		if i > 0 && i%2 == 0 {
			rowY += lineH
		}
		pdf.SetXY(x, rowY)
		pdf.SetFont("Arial", "B", 9)
		pdf.SetTextColor(80, 80, 80)
		pdf.Cell(30, lineH, pair.label)
		pdf.SetFont("Arial", "", 9)
		pdf.SetTextColor(33, 33, 33)
		pdf.Cell(0, lineH, " "+pair.value)
	}

	// --- FINANCIAL SUMMARY BOX ---
	drawSectionBox(pdf, 15, 105, 180, 45)
	pdf.SetFont("Arial", "B", 11)
	pdf.SetTextColor(23, 37, 84)
	pdf.SetXY(20, 109)
	pdf.Cell(0, 6, "Financial Summary")

	pdf.SetFont("Arial", "", 10)
	pdf.SetTextColor(33, 33, 33)
	financialRows := []struct{ label, value string }{
		{"Export Value (INR):", fmt.Sprintf("₹ %.2f", claim.ExportValueINR)},
		{"Export Quantity:", fmt.Sprintf("%v", claim.ExportQuantity)},
		{"Estimated Claim Amount:", fmt.Sprintf("₹ %.2f", claim.EstimatedClaimAmount)},
	}
	if claim.ApprovedClaimAmount != nil {
		financialRows = append(financialRows, struct{ label, value string }{
			"Approved Amount:", fmt.Sprintf("₹ %.2f", *claim.ApprovedClaimAmount),
		})
	}
	rowY = 118
	for _, row := range financialRows {
		pdf.SetXY(20, rowY)
		pdf.SetFont("Arial", "B", 9)
		pdf.SetTextColor(80, 80, 80)
		pdf.Cell(55, lineH, row.label)
		pdf.SetFont("Arial", "", 10)
		pdf.SetTextColor(33, 33, 33)
		pdf.Cell(0, lineH, "  "+row.value)
		rowY += lineH
	}

	// Highlight estimated amount
	pdf.SetXY(20, rowY+2)
	pdf.SetFillColor(220, 252, 231)
	pdf.SetDrawColor(34, 197, 94)
	pdf.SetLineWidth(0.5)
	pdf.Rect(20, rowY, 170, 10, "FD")
	pdf.SetFont("Arial", "B", 11)
	pdf.SetTextColor(22, 101, 52)
	pdf.SetXY(25, rowY+3)
	pdf.Cell(0, 5, fmt.Sprintf("TOTAL ESTIMATED CLAIM: ₹ %.2f", claim.EstimatedClaimAmount))

	// --- DOCUMENT CHECKLIST ---
	drawSectionBox(pdf, 15, 158, 180, 55)
	pdf.SetFont("Arial", "B", 11)
	pdf.SetTextColor(23, 37, 84)
	pdf.SetXY(20, 162)
	pdf.Cell(0, 6, "Required Documents Checklist")

	pdf.SetFont("Arial", "", 9)
	pdf.SetTextColor(33, 33, 33)
	rowY = 170
	for _, doc := range scheme.RequiredDocuments {
		docLabel := strings.ReplaceAll(doc, "_", " ")
		docLabel = strings.ToUpper(docLabel[:1]) + docLabel[1:]

		// Find if uploaded
		uploaded := false
		for _, cd := range claim.Documents {
			if cd.DocType == doc {
				uploaded = true
				break
			}
		}

		if uploaded {
			pdf.SetTextColor(22, 101, 52)
			pdf.SetXY(20, rowY)
			pdf.Cell(5, 5, "✓")
			pdf.SetTextColor(33, 33, 33)
			pdf.SetXY(26, rowY)
			pdf.Cell(0, 5, docLabel+" (UPLOADED)")
		} else {
			pdf.SetTextColor(180, 83, 9)
			pdf.SetXY(20, rowY)
			pdf.Cell(5, 5, "○")
			pdf.SetTextColor(33, 33, 33)
			pdf.SetXY(26, rowY)
			pdf.Cell(0, 5, docLabel+" (PENDING)")
		}
		rowY += 6
	}

	// --- NOTES ---
	if claim.Notes != "" {
		drawSectionBox(pdf, 15, 218, 180, 30)
		pdf.SetFont("Arial", "B", 10)
		pdf.SetTextColor(23, 37, 84)
		pdf.SetXY(20, 222)
		pdf.Cell(0, 5, "Notes")
		pdf.SetFont("Arial", "", 9)
		pdf.SetTextColor(33, 33, 33)
		pdf.SetXY(20, 229)
		pdf.MultiCell(170, 5, claim.Notes, "", "L", false)
	}

	// --- FOOTER ---
	pdf.SetFont("Arial", "I", 8)
	pdf.SetTextColor(150, 150, 150)
	pdf.SetXY(15, 280)
	pdf.Cell(0, 5, fmt.Sprintf("Generated by TRACE | %s | This is a system-generated document and does not require signature.", time.Now().Format("02-Jan-2006 15:04")))

	var buf bytes.Buffer
	if err := pdf.Output(&buf); err != nil {
		return nil, fmt.Errorf("failed to generate PDF: %w", err)
	}
	return &buf, nil
}

// GenerateClaimCSV produces a CSV export of a single claim (Excel-compatible).
func GenerateClaimCSV(claim *models.DGFTClaim, scheme *models.DGFTSchemeConfig, tenantName string) (*bytes.Buffer, error) {
	var buf bytes.Buffer
	w := csv.NewWriter(&buf)

	// Header section
	headers := [][]string{
		{"DGFT EXPORT INCENTIVE CLAIM"},
		{"Scheme", scheme.Name},
		{"Claim ID", claim.ID},
		{"Period", fmt.Sprintf("%s to %s", formatDateStr(claim.ClaimPeriodStart), formatDateStr(claim.ClaimPeriodEnd))},
		{"HSN Code", claim.HSNCode},
		{"Destination Country", claim.DestinationCountry},
		{"Exporter", tenantName},
		{"Status", claim.Status},
		{},
		{"Financial Summary"},
		{"Export Value (INR)", fmt.Sprintf("%.2f", claim.ExportValueINR)},
		{"Export Quantity", fmt.Sprintf("%v", claim.ExportQuantity)},
		{"Estimated Claim Amount", fmt.Sprintf("%.2f", claim.EstimatedClaimAmount)},
	}

	if claim.ApprovedClaimAmount != nil {
		headers = append(headers, []string{"Approved Amount", fmt.Sprintf("%.2f", *claim.ApprovedClaimAmount)})
	}

	headers = append(headers, []string{}, []string{"Required Documents"})
	for _, doc := range scheme.RequiredDocuments {
		docLabel := strings.ReplaceAll(doc, "_", " ")
		docLabel = strings.ToUpper(docLabel[:1]) + docLabel[1:]
		status := "PENDING"
		for _, cd := range claim.Documents {
			if cd.DocType == doc {
				status = "UPLOADED"
				break
			}
		}
		headers = append(headers, []string{docLabel, status})
	}

	if claim.Notes != "" {
		headers = append(headers, []string{}, []string{"Notes", claim.Notes})
	}

	headers = append(headers,
		[]string{},
		[]string{"Generated by TRACE", time.Now().Format("02-Jan-2006 15:04")},
	)

	for _, row := range headers {
		if err := w.Write(row); err != nil {
			return nil, fmt.Errorf("failed to write CSV: %w", err)
		}
	}
	w.Flush()
	if err := w.Error(); err != nil {
		return nil, fmt.Errorf("CSV writer error: %w", err)
	}
	return &buf, nil
}

// formatDateStr converts YYYY-MM-DD to DD-Mon-YYYY for display.
func formatDateStr(s string) string {
	t, err := time.Parse("2006-01-02", s)
	if err != nil {
		return s
	}
	return t.Format("02-Jan-2006")
}

// drawSectionBox draws a rounded-ish rectangle outline for section grouping.
func drawSectionBox(pdf *gofpdf.Fpdf, x, y, w, h float64) {
	pdf.SetDrawColor(220, 220, 220)
	pdf.SetLineWidth(0.3)
	pdf.Rect(x, y, w, h, "D")
	pdf.SetDrawColor(0, 0, 0)
}
