package services

import (
	"bytes"
	"encoding/json"
	"fmt"
	"strings"
	"time"

	"github.com/jung-kurt/gofpdf"

	"github.com/anvayalabs/textile-api/internal/models"
)

// GenerateTextileComplianceDeclaration creates a textile passport declaration PDF.
func GenerateTextileComplianceDeclaration(batch *models.Batch, tenant *models.Tenant) ([]byte, error) {
	tenant.EnsureTextileProfile()
	pdf := gofpdf.New("P", "mm", "A4", "")
	pdf.SetAutoPageBreak(true, 20)
	pdf.SetMargins(18, 20, 18)
	pdf.AddPage()

	pdf.SetFillColor(16, 64, 49)
	pdf.Rect(0, 0, 210, 34, "F")
	pdf.SetTextColor(255, 255, 255)
	pdf.SetFont("Helvetica", "B", 18)
	pdf.SetXY(18, 10)
	pdf.CellFormat(174, 9, "TEXTILE COMPLIANCE DECLARATION", "", 1, "L", false, 0, "")
	pdf.SetFont("Helvetica", "", 10)
	pdf.SetX(18)
	pdf.CellFormat(174, 6, "Product-aware textile passport declaration", "", 1, "L", false, 0, "")

	pdf.SetY(42)
	writeTextileKV := func(label, value string) {
		if strings.TrimSpace(value) == "" {
			return
		}
		pdf.SetFont("Helvetica", "B", 9)
		pdf.SetTextColor(55, 65, 81)
		pdf.CellFormat(45, 6, label+":", "", 0, "L", false, 0, "")
		pdf.SetFont("Helvetica", "", 9)
		pdf.SetTextColor(17, 24, 39)
		pdf.CellFormat(129, 6, value, "", 1, "L", false, 0, "")
	}

	pdf.SetFont("Helvetica", "B", 13)
	pdf.SetTextColor(22, 101, 52)
	pdf.CellFormat(174, 8, "Declaration Scope", "", 1, "L", false, 0, "")
	pdf.Ln(2)
	writeTextileKV("Generated", time.Now().Format("2006-01-02 15:04 UTC"))
	writeTextileKV("Manufacturer", tenant.CompanyName)
	writeTextileKV("Address", tenant.Address)
	writeTextileKV("Batch / Lot", batch.BatchName)
	writeTextileKV("Style / Product", batch.ModelName)
	writeTextileKV("Market Region", string(batch.MarketRegion))
	writeTextileKV("Material Profile", batch.Specs.MaterialProfile)
	writeTextileKV("Production Stage", batch.Specs.ProductionStage)

	writeTextileKV("Lot Size", batch.Specs.LotSize)
	writeTextileKV("Facility Type", tenant.TextileProfile.FacilityType)
	writeTextileKV("Supply Chain Tier", tenant.TextileProfile.SupplyChainTier)

	pdf.Ln(4)
	pdf.SetFont("Helvetica", "B", 13)
	pdf.SetTextColor(22, 101, 52)
	pdf.CellFormat(174, 8, "Declarations", "", 1, "L", false, 0, "")
	pdf.Ln(2)
	pdf.SetFont("Helvetica", "", 9)
	pdf.SetTextColor(17, 24, 39)

	pdf.MultiCell(174, 5, "REACH / SVHC declaration: No hazardous substances declaration supplied.", "", "L", false)
	pdf.Ln(1)

	pdf.MultiCell(174, 5, "Supply-chain due diligence policy: No due diligence policy URL supplied.", "", "L", false)

	if certifications := textileCertificationsSummary(batch, tenant); certifications != "" {
		pdf.Ln(3)
		pdf.MultiCell(174, 5, fmt.Sprintf("Certifications: %s", certifications), "", "L", false)
	}

	if complianceDefaults := textileComplianceDefaultsSummary(tenant); complianceDefaults != "" {
		pdf.Ln(3)
		pdf.MultiCell(174, 5, fmt.Sprintf("Tenant compliance defaults: %s", complianceDefaults), "", "L", false)
	}

	pdf.Ln(5)
	pdf.SetFont("Helvetica", "I", 8)
	pdf.SetTextColor(75, 85, 99)
	pdf.MultiCell(174, 4,
		"This textile declaration is generated by AnvayaLabs from the current tenant profile and lot data. It is a product passport support document and does not replace independent legal review or third-party certification where required.",
		"", "L", false,
	)

	var buf bytes.Buffer
	if err := pdf.Output(&buf); err != nil {
		return nil, fmt.Errorf("failed to generate textile compliance declaration PDF: %w", err)
	}
	return buf.Bytes(), nil
}

func textileCertificationsSummary(batch *models.Batch, tenant *models.Tenant) string {
	var certifications []string
	if len(tenant.TextileProfile.Certifications) > 0 {
		if err := json.Unmarshal(tenant.TextileProfile.Certifications, &certifications); err == nil && len(certifications) > 0 {
			return strings.Join(certifications, ", ")
		}
	}
	return ""
}

func textileComplianceDefaultsSummary(tenant *models.Tenant) string {
	if len(tenant.TextileProfile.ComplianceDefaults) == 0 {
		return ""
	}
	var defaults map[string]any
	if err := json.Unmarshal(tenant.TextileProfile.ComplianceDefaults, &defaults); err != nil || len(defaults) == 0 {
		return ""
	}
	parts := make([]string, 0, len(defaults))
	for key, value := range defaults {
		parts = append(parts, fmt.Sprintf("%s=%v", key, value))
	}
	return strings.Join(parts, ", ")
}